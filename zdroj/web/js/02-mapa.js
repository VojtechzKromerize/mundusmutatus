const NAMEPTS = [...PLACES.map(p => [p.name, p.lo, p.la]), ...TOWNS];
function nameOf(c) {
  let best = null,
    bd = 9;
  for (const [n, lo, la] of NAMEPTS) {
    const d = haversine(c, [lo, la]);
    if (d < bd) {
      bd = d;
      best = n;
    }
  }
  return best;
}
const KXc = 71.5,
  KYc = 111.2;
const MSEG = [];
MOUNTAINS.forEach(ch => {
  for (let i = 0; i < ch.length - 1; i++) MSEG.push([ch[i][0] * KXc, ch[i][1] * KYc, ch[i + 1][0] * KXc, ch[i + 1][1] * KYc]);
});
function nearMountain(lo, la) {
  const x = lo * KXc,
    y = la * KYc;
  for (const [x1, y1, x2, y2] of MSEG) {
    const dx = x2 - x1,
      dy = y2 - y1,
      L = dx * dx + dy * dy;
    let t = L ? ((x - x1) * dx + (y - y1) * dy) / L : 0;
    t = Math.max(0, Math.min(1, t));
    if (Math.hypot(x - (x1 + t * dx), y - (y1 + t * dy)) < 11) return true;
  }
  return false;
}
function terrain(a, b) {
  /* průliv bez přívozu (UZINY v 02e, 2026-10-27): po souši se přes něj nejde */
  if (presUzinu(a, b)) return Infinity;
  const km = haversine(a, b),
    n = Math.max(2, Math.ceil(km / 5));
  let sum = 0;
  for (let i = 0; i <= n; i++) {
    const lo = a[0] + ((b[0] - a[0]) * i) / n,
      la = a[1] + ((b[1] - a[1]) * i) / n;
    /* moře, zálivy a velká jezera (VODA_CESTA v 02e) jsou po souši neprůchodné – úsek přes ně se nepoužije */
    if (naVode(lo, la)) return Infinity;
    let f = 1;
    if (nearMountain(lo, la)) f = 2.0;
    else if (BAZINY.some(([, poly]) => inPoly(lo, la, poly))) f = 2.2;
    else if (FORESTS.some(poly => inPoly(lo, la, poly))) f = 1.7;
    else if (VRCHOVINY.some(([, poly]) => inPoly(lo, la, poly))) f = 1.3;
    sum += f;
  }
  return sum / (n + 1);
}
const RN = [],
  RADJ = [],
  OFF = 1.4; /* without a road even open country is slower */
function rNode(c) {
  for (let i = 0; i < RN.length; i++) if (haversine(RN[i], c) < 4) return i;
  RN.push(c);
  RADJ.push([]);
  return RN.length - 1;
}
function rLink(i, j, km, eff, road, lod) {
  const e = lod ? {km, eff, road, lod: true} : {km, eff, road};
  RADJ[i].push({to: j, ...e});
  RADJ[j].push({to: i, ...e});
}
/* síť cest pro měření trasy se spočítá až při prvním měření (2026-10-25): odhad terénu každého úseku je na startu webu
   nejdražší výpočet jádra (~0,1 s na telefonu) a většina návštěv mapu neměří */
let RSIT = false;
function cestySit() {
  if (RSIT) return;
  RSIT = true;
  for (const [, line, , lod] of ROADS)
    for (let i = 0; i < line.length - 1; i++) {
      const a = rNode(line[i]),
        b = rNode(line[i + 1]);
      if (a === b) continue;
      /* přívoz a lodní spoj (2026-10-27): úsek přes vodu, terén se nepočítá; čekání na převoz jako ~8 km cesty */
      if (lod) {
        const km = haversine(RN[a], RN[b]);
        rLink(a, b, km, km * 1.5 + 8, true, true);
        continue;
      }
      const km = haversine(RN[a], RN[b]) * 1.15,
        t = terrain(RN[a], RN[b]);
      rLink(a, b, km, km * (1 + (t - 1) * 0.35), true);
    }
  for (let i = 0; i < RN.length; i++)
    for (let j = i + 1; j < RN.length; j++) {
      const d = haversine(RN[i], RN[j]);
      if (d < 30 && !RADJ[i].some(e => e.to === j)) {
        const km = d * 1.3;
        rLink(i, j, km, km * terrain(RN[i], RN[j]) * OFF, false);
      }
    }
}
function computeRoute(A, B) {
  cestySit();
  const a = [A.lo, A.la],
    b = [B.lo, B.la],
    N = RN.length,
    ia = N,
    ib = N + 1;
  const coords = [...RN, a, b],
    adj = RADJ.map(l => l.slice());
  adj.push([], []);
  const link = (i, j, km, eff, road) => {
    adj[i].push({to: j, km, eff, road});
    adj[j].push({to: i, km, eff, road});
  };
  for (const [idx, pt] of [
    [ia, a],
    [ib, b],
  ]) {
    RN.map((c, i) => [i, haversine(c, pt)])
      .sort((x, y) => x[1] - y[1])
      .slice(0, 4)
      .forEach(([i, d]) => {
        const km = d * 1.3;
        link(idx, i, km, km * terrain(pt, RN[i]) * OFF, false);
      });
  }
  {
    const d = haversine(a, b),
      km = d * 1.3;
    link(ia, ib, km, km * terrain(a, b) * OFF, false);
  }
  const dist = Array(N + 2).fill(Infinity),
    prev = Array(N + 2).fill(null),
    done = Array(N + 2).fill(false);
  dist[ia] = 0;
  for (;;) {
    let u = -1,
      bd = Infinity;
    for (let i = 0; i < N + 2; i++)
      if (!done[i] && dist[i] < bd) {
        bd = dist[i];
        u = i;
      }
    if (u < 0 || u === ib) break;
    done[u] = true;
    for (const e of adj[u]) {
      const nd = dist[u] + e.eff;
      if (nd < dist[e.to]) {
        dist[e.to] = nd;
        prev[e.to] = {from: u, e};
      }
    }
  }
  /* cíl jen přes vodu (ostrov, druhý břeh zálivu bez cesty kolem): trasa po souši není */
  if (!isFinite(dist[ib])) return null;
  const path = [ib],
    legs = [];
  let roadKm = 0,
    offKm = 0;
  let cur = ib;
  while (prev[cur]) {
    const {from, e} = prev[cur];
    if (e.road) roadKm += e.km;
    else offKm += e.km;
    legs.unshift(
      e.lod
        ? {p0: coords[from], p1: coords[cur], km: e.km, eff: e.eff, road: e.road, lod: true}
        : {p0: coords[from], p1: coords[cur], km: e.km, eff: e.eff, road: e.road},
    );
    path.push(from);
    cur = from;
  }
  path.reverse();
  const names = [];
  for (const i of path) {
    const n = i === ia ? A.name : i === ib ? B.name : nameOf(coords[i]);
    if (n && names[names.length - 1] !== n) names.push(n);
  }
  return {
    coords: path.map(i => coords[i]),
    km: Math.round(roadKm + offKm),
    roadKm: Math.round(roadKm),
    offKm: Math.round(offKm),
    eff: dist[ib],
    names,
    legs,
  };
}
