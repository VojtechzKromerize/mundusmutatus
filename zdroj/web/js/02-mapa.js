let GROZ = false;
function grafRozloz() {
  if (GROZ) return;
  GROZ = true;
  const anc = {};
  for (const id of GIDS) {
    const f = byId[id];
    anc[id] = f.seats.length ? [f.seats[0][1], f.seats[0][2]] : [11.3, 47.6];
  }
  const lons = Object.values(anc).map(a => a[0]),
    lats = Object.values(anc).map(a => a[1]);
  const lo0 = Math.min(...lons),
    lo1 = Math.max(...lons),
    la0 = Math.min(...lats),
    la1 = Math.max(...lats);
  for (const id of GIDS) {
    const [lo, la] = anc[id];
    const ax = 70 + ((lo - lo0) / (lo1 - lo0)) * (GW - 170),
      ay = 40 + ((la1 - la) / (la1 - la0)) * (GH - 80);
    GN[id] = {id, ax, ay, x: ax, y: ay, deg: 0};
  }
  EDGES.forEach(e => {
    GN[e.a].deg++;
    GN[e.b].deg++;
  });
  const nodes = Object.values(GN);
  for (let it = 0; it < 500; it++) {
    const cool = 1 - it / 500;
    for (let i = 0; i < nodes.length; i++)
      for (let j = i + 1; j < nodes.length; j++) {
        const p = nodes[i],
          q = nodes[j];
        let dx = p.x - q.x,
          dy = p.y - q.y;
        let d2 = dx * dx + dy * dy;
        if (d2 < 1) {
          dx = i % 2 ? 1 : -1;
          dy = 1;
          d2 = 2;
        }
        if (d2 > 90000) continue;
        const f = Math.min(5200 / d2, 10) * (0.3 + cool),
          d = Math.sqrt(d2);
        p.x += (dx / d) * f;
        p.y += (dy / d) * f;
        q.x -= (dx / d) * f;
        q.y -= (dy / d) * f;
      }
    for (const e of EDGES) {
      const p = GN[e.a],
        q = GN[e.b];
      const dx = q.x - p.x,
        dy = q.y - p.y,
        d = Math.sqrt(dx * dx + dy * dy) || 1;
      const f = (d - 110) * 0.004 * cool;
      p.x += (dx / d) * f;
      p.y += (dy / d) * f;
      q.x -= (dx / d) * f;
      q.y -= (dy / d) * f;
    }
    for (const n of nodes) {
      n.x += (n.ax - n.x) * 0.008;
      n.y += (n.ay - n.y) * 0.008;
    }
    /* keep labels (drawn to the right of each node) from overlapping */
    for (let i = 0; i < nodes.length; i++)
      for (let j = 0; j < nodes.length; j++) {
        if (i === j) continue;
        const p = nodes[i],
          q = nodes[j];
        const w = (SHORT[p.id] || "").length * 7 + 22;
        const dx = q.x - p.x,
          dy = q.y - p.y;
        if (dx > -14 && dx < w && Math.abs(dy) < 17) {
          const push = (17 - Math.abs(dy)) * 0.25;
          const s = dy >= 0 ? 1 : -1;
          q.y += s * push;
          p.y -= s * push;
        }
      }
    for (const n of nodes) {
      n.x = Math.max(20, Math.min(GW - 150, n.x));
      n.y = Math.max(18, Math.min(GH - 18, n.y));
    }
  }
}
