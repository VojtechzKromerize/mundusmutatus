/* meander: densify a line and push it sideways with smooth pseudo-noise, so rivers wander like hand-drawn ones */
function meander(line, amp, seed) {
  const out = [];
  let sd = seed;
  const rnd = () => {
    sd = (sd * 16807) % 2147483647;
    return sd / 2147483647;
  };
  const ph1 = rnd() * 6.28,
    ph2 = rnd() * 6.28;
  let acc = 0;
  for (let i = 0; i < line.length - 1; i++) {
    const [x1, y1] = line[i],
      [x2, y2] = line[i + 1],
      L = Math.hypot(x2 - x1, y2 - y1),
      n = Math.max(2, Math.round(L / (amp * 2.2)));
    const nx = -(y2 - y1) / (L || 1),
      ny = (x2 - x1) / (L || 1);
    for (let j = 0; j < n; j++) {
      const t = j / n,
        x = x1 + (x2 - x1) * t,
        y = y1 + (y2 - y1) * t;
      acc += L / n;
      const o = amp * (0.65 * Math.sin(acc / (amp * 3.1) + ph1) + 0.35 * Math.sin(acc / (amp * 1.3) + ph2));
      const fade = i === 0 && j === 0 ? 0 : 1;
      out.push([x + nx * o * fade, y + ny * o * fade]);
    }
  }
  out.push(line[line.length - 1]);
  return out;
}
